function packageRoot(): string {
  const moduleUrl = (import.meta as unknown as { url: string }).url;
  const modulePath = decodeURIComponent(moduleUrl.replace(/^file:\/\//, ""));
  if (modulePath.includes("/dist/src/")) return modulePath.split("/dist/src/")[0];
  if (modulePath.includes("/src/")) return modulePath.split("/src/")[0];
  return join(dirname(modulePath), "../../../");
}

async function firstExisting(paths: string[]): Promise<string | null> {
  for (const path of paths) {
    try {
      await access(path);
      return path;
    } catch {
      // Try the next known Panda output location.
    }
  }
  return null;
}

