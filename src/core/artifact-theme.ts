export async function prepareArtifactTheme(cwd: string, artifactDir: string): Promise<ArtifactTheme> {
  await mkdir(artifactDir, { recursive: true });
  const cssPath = join(artifactDir, ARTIFACT_THEME_FILENAME);
  const source = await firstExisting([
    join(cwd, "web", "styled-system", "styles.css"),
    join(cwd, "web", "src", "styled-system", "styles.css"),
    join(cwd, "styled-system", "styles.css"),
    join(packageRoot(), "web", "styled-system", "styles.css"),
    join(packageRoot(), "web", "src", "styled-system", "styles.css")
  ]);

  if (source) {
    await copyFile(source, cssPath);
    return {
      cssPath,
      href: importHref(artifactDir, cssPath),
      source: "panda"
    };
  }

  await writeFile(cssPath, fallbackArtifactThemeCss(), "utf8");
  return {
    cssPath,
    href: importHref(artifactDir, cssPath),
    source: "fallback"
  };
}

function importHref(fromDir: string, targetPath: string): string {
  const href = relative(fromDir, targetPath).replaceAll("\\", "/");
  return href.startsWith(".") ? href : `./${href}`;
}
