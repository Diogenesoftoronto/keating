// node glyphs-to-app.mjs <glyphs.mjs> <out data.ts>
// Regenerates the app's glyph data from the design source, so the mockups and the app draw from one file.
import { writeFileSync } from "node:fs";
const [src, out] = process.argv.slice(2);
const { GLYPHS, GROUPS, LABELS } = await import(src);

function parse(fragment) {
  const nodes = []; const stack = [nodes];
  const re = /<(\/?)(g|path|rect)([^>]*?)(\/?)>/g; let m;
  while ((m = re.exec(fragment))) {
    const [, closing, tag, raw, selfClosing] = m;
    if (closing) { stack.pop(); continue; }
    const attrs = {}; for (const a of raw.matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    const role = attrs.class === "a" ? "accent" : attrs.class === "af" ? "accentFill" : attrs.class === "f" ? "fill" : "stroke";
    const node = { tag, role, attributes: {} };
    for (const key of ["d", "x", "y", "width", "height", "transform"]) if (attrs[key] !== undefined) node.attributes[key] = attrs[key];
    if (attrs["data-p"]) node.part = attrs["data-p"];
    const origin = /transform-origin:\s*([^;"]+)/.exec(attrs.style ?? "");
    if (origin) node.origin = origin[1].trim();
    stack[stack.length - 1].push(node);
    if (tag === "g" && !selfClosing) { node.children = []; stack.push(node.children); }
  }
  if (stack.length !== 1) throw new Error("unbalanced groups in " + fragment);
  return nodes;
}
const q = (v) => JSON.stringify(v);
const obj = (o) => "{" + Object.entries(o).map(([k, v]) => `${k}: ${Array.isArray(v) ? "[" + v.map(q).join(", ") + "]" : q(v)}`).join(", ") + "}";
function node(n, indent) {
  let s = `${indent}{tag: ${q(n.tag)}, role: ${q(n.role)}, attributes: ${obj(n.attributes)}`;
  if (n.part) s += `, part: ${q(n.part)}`;
  if (n.origin) s += `, origin: ${q(n.origin)}`;
  if (n.children) s += `, children: [\n${n.children.map((c) => node(c, indent + "  ")).join("\n")}\n${indent}]`;
  return s + "},";
}
const step = ([parts, frames, options]) => `[${q(parts)}, ${obj(frames)}${options ? ", " + obj(options) : ""}]`;
let ts = `// Generated from docs/design/2026-11-19-review-chat-mockups/src/glyphs.mjs by src/tools/glyphs-to-app.mjs.\n// Edit the drawings there and regenerate; do not edit this file by hand.\nimport type { GlyphDefinition } from "./types";\n\nconst definitions = {\n`;
for (const [name, g] of Object.entries(GLYPHS)) {
  ts += `  ${name}: {\n    nodes: [\n${parse(g.d).map((n) => node(n, "      ")).join("\n")}\n    ],\n`;
  for (const key of Object.keys(g)) if (["play", "hold", "loop", "press"].includes(key)) ts += `    ${key}: [${g[key].map(step).join(", ")}],\n`;
  ts += `    note: ${q(g.note)},\n  },\n`;
}
ts += `} satisfies Record<string, GlyphDefinition>;\n\nexport type GlyphName = keyof typeof definitions;\nexport const GLYPHS: Record<GlyphName, GlyphDefinition> = definitions;\nexport const GLYPH_NAMES = Object.keys(definitions) as GlyphName[];\n\nexport const GROUPS = [\n`;
for (const [title, names] of GROUPS) ts += `  [${q(title)}, [${names.map(q).join(", ")}]],\n`;
ts += `] as const satisfies readonly (readonly [string, readonly GlyphName[]])[];\n\nexport const LABELS = {\n`;
for (const name of Object.keys(GLYPHS)) ts += `  ${name}: ${q(LABELS[name])},\n`;
ts += `} satisfies Record<GlyphName, string>;\n`;
writeFileSync(out, ts);
console.log(`wrote ${Object.keys(GLYPHS).length} glyphs to ${out}`);
