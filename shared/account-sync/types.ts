/** Version-independent wire types. SDK-specific validation belongs to each client. */
export type ThinkingLevel = string;
export interface SyncMessage { role: string; content?: unknown; timestamp?: number | string }
export interface SyncModel {
  id: string; provider: string; name?: string; api?: string; reasoning?: boolean;
  input?: readonly string[]; contextWindow?: number; maxTokens?: number; baseUrl?: string;
  cost?: { input: number; output: number; cacheRead: number; cacheWrite: number };
  compat?: unknown;
}
export interface NativeSessionTree {
  header: Record<string, unknown>;
  entries: unknown[];
  leafId: string | null;
}

export interface SessionUsage {
	input: number;
	output: number;
	cacheRead: number;
	cacheWrite: number;
	totalTokens: number;
	cost: {
		input: number;
		output: number;
		cacheRead: number;
		cacheWrite: number;
		total: number;
	};
}

export interface SessionMetadata {
	id: string;
	title: string;
	parentSessionId?: string | null;
	forkedAt?: string;
	forkedFromMessageTimestamp?: number;
	createdAt: string;
	lastModified: string;
	messageCount: number;
	usage: SessionUsage;
	thinkingLevel: ThinkingLevel;
	modelProvider?: string;
	modelId?: string;
	modelName?: string;
	modelApi?: string;
	modelReasoning?: boolean;
	preview: string;
	/** Full plain-text message corpus for local session search. */
	searchText?: string;
	/** Whether the title was generated by AI (blocks manual rename until true). */
	aiGeneratedTitle?: boolean;
	/** Internal counterfactual generated for an explicit learner comparison. */
	generatedAlternative?: boolean;
	/** Keep unselected counterfactuals out of the normal session browser. */
	hiddenAlternative?: boolean;
	alternativeForMessageTimestamp?: number;
	responsePreference?: "original" | "alternative" | "skipped";
}

export interface SessionData {
	id: string;
	title: string;
	parentSessionId?: string | null;
	forkedAt?: string;
	forkedFromMessageTimestamp?: number;
	model: SyncModel;
	thinkingLevel: ThinkingLevel;
	messages: SyncMessage[];
	/** Complete native session tree, retained even by clients that render only its selected branch. */
	nativeSession?: NativeSessionTree;
	createdAt: string;
	lastModified: string;
	/** Mirrors metadata.aiGeneratedTitle for round-trip persistence. */
	aiGeneratedTitle?: boolean;
	generatedAlternative?: boolean;
	hiddenAlternative?: boolean;
	alternativeForMessageTimestamp?: number;
	responsePreference?: "original" | "alternative" | "skipped";
}

export interface KeatingPortableSession { data: SessionData; metadata: SessionMetadata }
