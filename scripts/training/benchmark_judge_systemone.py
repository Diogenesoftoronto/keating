def validate_backend(manifest):
    """Reuse the existing classifier identity contract instead of inventing a second one.

    `benchmark_response_grading.validate_classifier` pins its own protocol string, so the
    delegated copy carries that value while the caller's manifest must declare this
    module's protocol. Field names, permitted kinds, hash formats and the confidence floor
    are all checked by that one validator, which is what keeps `calibration_sha256` a
    cross-language check rather than a convention. Reached over HTTP the judgement model is
    an ordinary `model_api`; adding a new kind would break the existing validator.
    """
    bench.require(isinstance(manifest, dict) and "protocol" in manifest,
                  "Backend manifest requires a declared protocol")
    grading.validate_classifier({**manifest, "protocol": grading.PROTOCOL})
    bench.require(manifest["protocol"] == PROTOCOL, "Judgement protocol required")
    return manifest


def default_manifest(judge_model=SYSTEM_ONE_MODEL, *, kind="model_api",
                     minimum_confidence=DEFAULT_MINIMUM_CONFIDENCE, calibration_sha256=None):
    """A hosted model has no downloadable artifact, so the artifact pin is an identity pin
    over everything that changes its answers: model, protocol and the authored question text.
    `calibration_sha256` stays None until thresholds are fitted against this exact backend."""
    artifact = bench.digest(bench.canonical({
        "model": judge_model, "protocol": PROTOCOL, "prompt_version": PROMPT_VERSION,
        "prompt_sha256": PROMPT_SHA256, "settings": SETTINGS}))
    manifest = {"kind": kind, "id": judge_model, "revision": PROMPT_VERSION, "protocol": PROTOCOL,
                "artifact_sha256": artifact, "calibration_sha256": calibration_sha256,
                "minimum_confidence": minimum_confidence}
    return validate_backend(manifest)


# ---------------------------------------------------------------------------------------
# Candidate enumeration: code owns every span a rating can ever cite.
# ---------------------------------------------------------------------------------------

def evidence_text(message):
    """Exactly the text the incumbent validator searches.

    `validate_ratings` proves a quote by `quote in text` against this composition, so
    enumeration has to build the identical string or a selected span could fail its own
    verification. The two must always move together.
    """
    content = message.get("content")
    text = content if isinstance(content, str) else bench.canonical(content)
    text += "\n" + bench.canonical(message.get("tool_calls", []))
    # Include literal JSON argument strings, preserving exact quotes rather than escaped
    # serialization.
    for call in message.get("tool_calls", []):
        args = call.get("function", {}).get("arguments")
        if isinstance(args, str):
            text += "\n" + args
    return text


def trim_span(text, start, end):
    """Shrink a span past surrounding whitespace so `text[start:end]` is the exact quote."""
    while start < end and text[start].isspace():
        start += 1
    while end > start and text[end - 1].isspace():
        end -= 1
    return (start, end) if end > start else None


SENTENCE_BREAK = re.compile(r"(?<=[.!?])\s+|\n+")


def sentence_spans(text):
    """Deterministic, offset-exact sentence spans in document order."""
    spans, start, out = [], 0, []
    for match in SENTENCE_BREAK.finditer(text):
        spans.append((start, match.start()))
        start = match.end()
    spans.append((start, len(text)))
    for begin, end in spans:
        trimmed = trim_span(text, begin, end)
        if trimmed is not None:
            out.append(trimmed)
    return out


def candidate_items(transcript):
    """Every quotable candidate item, deduped by exact text, in document order.

    Only assistant and tool items are enumerated. The fixed learner prefix is not a
    candidate, so a rating physically cannot cite the learner's own words back at them.
    """
    items, seen = [], set()
    for index, message in enumerate(transcript):
        if not isinstance(message, dict) or message.get("role") not in EVIDENCE_ROLES:
            continue
        try:
            text = evidence_text(message)
        except Exception:
            # A malformed item yields no candidates rather than failing the whole review.
            continue
        span = trim_span(text, 0, len(text))
        if span is None:
            continue
        value = text[span[0]:span[1]]
        if value in seen:
            continue
        seen.add(value)
        items.append({"key": f"i{index}", "transcript_index": index,
                      "start": span[0], "end": span[1], "text": value})
    return items


def candidate_sentences(transcript, item):
    """Sentence-level candidates inside one already-selected item, deduped, document order."""
    text = evidence_text(transcript[item["transcript_index"]])
    out, seen = [], set()
    for start, end in sentence_spans(text):
        value = text[start:end]
        if value in seen:
            continue
        seen.add(value)
        out.append({"key": f"s{start}", "transcript_index": item["transcript_index"],
                    "start": start, "end": end, "text": value})
    return out


def resolve_span(transcript, candidate):
    """Re-extract the span from the transcript and refuse anything that does not match.

    The extraction is the authority, not the option label: an elided preview shown to the
    backend can never corrupt the quote that lands in the receipt.
    """
    message = transcript[candidate["transcript_index"]]
    bench.require(message.get("role") in EVIDENCE_ROLES,
                  "Evidence must come from candidate/tool output")
    text = evidence_text(message)
    quote = text[candidate["start"]:candidate["end"]]
    bench.require(bool(quote.strip()) and quote == candidate["text"] and quote in text,
                  "Selected evidence span did not resolve")
    return quote


def candidate_tree(items, usable):
    """Nest candidates into groups until the top level fits inside one Choice.

    A flat list is returned unchanged, which is the ordinary case. Past the option cap the
    list becomes contiguous groups, so narrowing is group then item (then sentence) rather
    than a truncated option set that silently drops evidence.
    """
    bench.require(usable >= 2, "A Choice needs at least two options")
    nodes = list(items)
    while len(nodes) > usable:
        size = math.ceil(len(nodes) / usable)
        nodes = [{"group": nodes[index:index + size]} for index in range(0, len(nodes), size)]
    return nodes


def leaves(node):
    if "group" not in node:
        return [node]
    return [leaf for child in node["group"] for leaf in leaves(child)]


def preview(text, limit=OPTION_PREVIEW_CHARS):
    """A readable option label. Never the source of a quote; offsets are."""
    collapsed = " ".join(text.split())
    return collapsed if len(collapsed) <= limit else collapsed[:limit - 1] + "\u2026"


