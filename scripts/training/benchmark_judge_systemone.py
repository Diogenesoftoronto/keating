def dimension_anchors(spec):
    """The ordered 0/1/2 anchors, worst level first."""
    value = spec.get("criteria") if isinstance(spec, dict) and isinstance(spec.get("criteria"), dict) else spec
    bench.require(isinstance(value, dict), "Rubric dimension must describe its anchors")
    anchors = []
    for names in ANCHOR_KEYS:
        found = next((value[name] for name in names
                      if isinstance(value.get(name), str) and value[name].strip()), None)
        bench.require(found is not None, "Rubric dimension needs ordered 0/1/2 anchors")
        anchors.append(found)
    return anchors


def dimension_label(name, spec):
    label = spec.get("label") if isinstance(spec, dict) else None
    return label if isinstance(label, str) and label.strip() else name


def dimension_prefix(dimension):
    return f'{REVIEW_NOTICE} {DATA_NOTICE} Rubric dimension "{dimension["label"]}".'


def score_question(dimension):
    return {"type": "score", "instructions": f"{dimension_prefix(dimension)} {SCORE_INSTRUCTIONS}",
            "criteria": list(dimension["anchors"])}


def judgeable_question(dimension):
    # One Noul, one direction: `true` describes the yes case. A Noul for the claim and a
    # second for its negation do not sum to one and must never both be asked.
    return {"type": "noul",
            "instructions": f"{dimension_prefix(dimension)} {JUDGEABLE_INSTRUCTIONS}",
            "criteria": dict(JUDGEABLE_CRITERIA)}


def support_question(dimension):
    return {"type": "choice",
            "instructions": f"{dimension_prefix(dimension)} {SUPPORT_INSTRUCTIONS}",
            "criteria": dict(SUPPORT_CRITERIA)}


def evidence_question(dimension, cursor):
    """The Choice for the current narrowing stage, or None when nothing is selectable.

    Returns None rather than a one-option Choice when a transcript has no candidate items:
    an unanswerable question is worse than an honest absence, and the caller already knows
    how to treat a missing evidence answer.
    """
    nodes = cursor["nodes"]
    if not nodes:
        return None
    criteria, options = {}, {}
    sentences = cursor["phase"] == "sentences"
    grouped = any("group" in node for node in nodes)
    if sentences:
        instructions = EVIDENCE_SENTENCE_INSTRUCTIONS
    elif grouped:
        instructions = EVIDENCE_GROUP_INSTRUCTIONS
    else:
        instructions = EVIDENCE_INSTRUCTIONS
    for position, node in enumerate(nodes):
        if "group" in node:
            key = f"g{position}"
            span = leaves(node)
            label = (f'Candidate items {span[0]["transcript_index"]}-'
                     f'{span[-1]["transcript_index"]}, starting "{preview(span[0]["text"], 120)}"')
        elif sentences:
            key = node["key"]
            label = f'Sentence {position + 1}: {preview(node["text"])}'
        else:
            key = node["key"]
            label = f'Candidate item {node["transcript_index"]}: {preview(node["text"])}'
        criteria[key] = label
        options[key] = node
    if sentences:
        criteria[WHOLE_ITEM] = WHOLE_ITEM_CRITERION
        options[WHOLE_ITEM] = cursor["item"]
    criteria[NO_MATCH] = NO_MATCH_CRITERION
    bench.require(len(criteria) <= MAX_CHOICE_OPTIONS, "Choice exceeded the option cap")
    cursor["options"] = options
    return {"type": "choice",
            "instructions": f"{dimension_prefix(dimension)} {instructions}",
            "criteria": criteria}


def evidence_key(dimension, stage):
    return f'd{dimension["index"]}.evidence.{stage}'


def review_material(case, transcript):
    """The same untrusted-material projection the incumbent reviewer assembles.

    Imported lazily so this module carries no import-time dependency on the CLI module and
    the two can never form a cycle.
    """
    import benchmark_judge
    return benchmark_judge.material(case, transcript)


def build_plan(case, transcript, *, judge_model=SYSTEM_ONE_MODEL, state=None):
    """Everything the review needs that does not depend on an answer.

    Deterministic given `(case, transcript)`, which is what lets a taped A/B replay hold the
    judge's input fixed while only the backend changes.
    """
    rubric = case.get("rubric")
    bench.require(isinstance(rubric, dict) and rubric, "Case rubric required")
    state = review_material(case, transcript) if state is None else state
    # State is assembled, never dumped. Over budget we abstain rather than judge a
    # truncated transcript, because a silently shortened prefix is unverifiable evidence.
    bench.require(len(bench.canonical(state)) <= MAX_STATE_CHARS,
                  "Judgement state exceeds the assembled-state budget")
    items = candidate_items(transcript)
    nodes = candidate_tree(items, MAX_CHOICE_OPTIONS - 1) if items else []
    dimensions = []
    for index, name in enumerate(rubric):
        spec = rubric[name]
        dimensions.append({"dimension": name, "index": index,
                           "label": dimension_label(name, spec),
                           "anchors": dimension_anchors(spec)})
    return {"protocol": PROTOCOL, "prompt_version": PROMPT_VERSION, "model": judge_model,
            "state": state, "dimensions": dimensions, "candidates": items, "nodes": nodes,
            "narrowed": bool(items) and any("group" in node for node in nodes)}


def new_cursor(plan):
    return {"phase": "items", "nodes": list(plan["nodes"]), "stage": 1, "item": None,
            "selected": None, "resolved": False, "options": {}, "stages": []}


def first_round_questions(plan, cursors):
    """The four questions per dimension, keyed so answers round-trip by dimension index."""
    questions = {}
    for dimension in plan["dimensions"]:
        index = dimension["index"]
        questions[f"d{index}.score"] = score_question(dimension)
        questions[f"d{index}.judgeable"] = judgeable_question(dimension)
        questions[f"d{index}.support"] = support_question(dimension)
        cursor = cursors[index]
        question = evidence_question(dimension, cursor)
        if question is None:
            cursor["resolved"] = True
        else:
            cursor["stages"].append("group" if any("group" in n for n in cursor["nodes"]) else "item")
            questions[evidence_key(dimension, cursor["stage"])] = question
    return questions


def batch_questions(questions, limit=MAX_QUESTIONS_PER_REQUEST):
    """Split a question map into requests that respect the batch guardrail."""
    bench.require(limit >= 1, "A request carries at least one question")
    keys = list(questions)
    return [{key: questions[key] for key in keys[start:start + limit]}
            for start in range(0, len(keys), limit)]


def request_body(questions, plan):
    bench.require(len(questions) <= MAX_QUESTIONS_PER_REQUEST,
                  "Judgement request exceeds the batch guardrail")
    return {"state": copy.deepcopy(plan["state"]), "model": plan["model"],
            "questions": copy.deepcopy(questions)}


def build_request(case, transcript, judge_model=SYSTEM_ONE_MODEL, *, state=None):
    """The first-round request body, for dry runs and request hashing."""
    plan = build_plan(case, transcript, judge_model=judge_model, state=state)
    cursors = {dimension["index"]: new_cursor(plan) for dimension in plan["dimensions"]}
    return request_body(first_round_questions(plan, cursors), plan)


def build_requests(case, transcript, judge_model=SYSTEM_ONE_MODEL, *, state=None):
    """Every first-round request. One entry unless the rubric exceeds the batch guardrail."""
    plan = build_plan(case, transcript, judge_model=judge_model, state=state)
    cursors = {dimension["index"]: new_cursor(plan) for dimension in plan["dimensions"]}
    questions = first_round_questions(plan, cursors)
    return [request_body(batch, plan) for batch in batch_questions(questions)]


# ---------------------------------------------------------------------------------------
# Answer decoding: a mirror of `wire.ts`, where a shape mismatch is malformed, not repaired.
# ---------------------------------------------------------------------------------------

def probability(value):
    # `bool` is excluded on purpose: True is not a probability of 1.
    return type(value) in (int, float) and math.isfinite(value) and 0 <= value <= 1


def decode_probabilities(value):
    if not isinstance(value, dict) or not value:
        return None
    out = {}
    for key, entry in value.items():
        if not isinstance(key, str) or not probability(entry):
            return None
        out[key] = float(entry)
    return out


def decode_legend(value):
    if not isinstance(value, dict):
        return None
    if any(not isinstance(key, str) or not isinstance(entry, str) for key, entry in value.items()):
        return None
    return dict(value)


def decode_answer(question, value):
    """Decode one answer, or None when it does not match the primitive that was asked."""
    if not isinstance(value, dict) or value.get("type") != question["type"]:
        return None
    if question["type"] == "noul":
        # A Noul deliberately has no confidence field; one must not be invented.
        return {"type": "noul", "noul": float(value["noul"])} if probability(value.get("noul")) else None
    probabilities = decode_probabilities(value.get("probabilities"))
    if probabilities is None or not probability(value.get("confidence")):
        return None
    if question["type"] == "choice":
        choice = value.get("choice")
        if not isinstance(choice, str) or choice not in question["criteria"]:
            return None
        return {"type": "choice", "choice": choice, "probabilities": probabilities,
                "confidence": float(value["confidence"])}
    legend = decode_legend(value.get("legend"))
    score = value.get("score")
    if legend is None or type(score) not in (int, float) or not math.isfinite(score):
        return None
    return {"type": "score", "score": float(score), "legend": legend,
            "probabilities": probabilities, "confidence": float(value["confidence"])}


def decode_response(questions, raw):
    """Decode a whole response. Unknown keys are dropped; a missing key stays absent.

    The upstream body is never read for a message. Error text can echo the learner's own
    words straight back, so only our own authored string ever leaves this function.
    """
    bench.require(isinstance(raw, dict), "Judgement response malformed")
    bench.require(not raw.get("error"), "Judgement backend returned an error")
    body = raw.get("answers")
    bench.require(isinstance(body, dict), "Judgement response malformed")
    answers = {}
    for key, question in questions.items():
        if key not in body:
            continue
        decoded = decode_answer(question, body[key])
        if decoded is not None:
            answers[key] = decoded
    usage = raw.get("usage")
    return answers, usage if isinstance(usage, dict) else None


def ordered_levels(answer):
    """Level probabilities in level order, independent of key insertion order."""
    pairs = []
    for level, value in answer["probabilities"].items():
        try:
            pairs.append((int(level), value))
        except (TypeError, ValueError):
            continue
    return [value for _, value in sorted(pairs)]


def modal_level(answer):
    """The level actually carrying the most mass, or None when no level does.

    Decisions read this rather than `score`: the weighted mean can name a level nobody
    chose, and score levels are weak in numerical calibration.
    """
    ordered = ordered_levels(answer)
    if not ordered:
        return None
    best = 0
    for index in range(1, len(ordered)):
        if ordered[index] > ordered[best]:
            best = index
    return best


def is_bimodal(answer, trough_ratio=0.5):
    """True when the mean sits in a trough between two non-adjacent peaks."""
    ordered = ordered_levels(answer)
    if len(ordered) < 3:
        return False
    ranked = sorted(enumerate(ordered), key=lambda pair: pair[1], reverse=True)
    (first, first_value), (second, second_value) = ranked[0], ranked[1]
    if second_value <= 0:
        return False
    low, high = min(first, second), max(first, second)
    if high - low < 2:
        return False
    trough = min(ordered[index] for index in range(low + 1, high))
    return trough <= trough_ratio * second_value


def modal_option(answer):
    """Argmax over the distribution, falling back to the declared selection."""
    best, best_value = answer["choice"], answer["probabilities"].get(answer["choice"], -1.0)
    for option, value in answer["probabilities"].items():
        if value > best_value:
            best, best_value = option, value
    return best


def noul_decision(answer, band):
    """Yes / no / uncertain. Around 0.5 a Noul refuses to commit; that is not half a yes."""
    if answer["noul"] >= band["yes_at_or_above"]:
        return "yes"
    if answer["noul"] <= band["no_at_or_below"]:
        return "no"
    return "uncertain"


