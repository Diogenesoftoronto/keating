#!/usr/bin/env python3
"""Typed judgement backend for the teaching rubric review: evidence by selection.

The incumbent reviewer in `benchmark_judge.py` asks a generative model for JSON and then
tries to prove that the quote it wrote down actually exists. This module inverts that
flow. Code enumerates the candidate spans, the judgement backend *selects* one by key,
and code extracts the span byte-for-byte. A selected key always resolves, so the whole
"the model invented a quote" failure class stops existing.

Per rubric dimension the batch carries four typed questions:

  * Score  over the dimension's ordered 0/1/2 anchors,
  * Noul   "this dimension can be judged from the evidence available",
  * Choice over code-enumerated candidate spans plus an explicit no-match sentinel,
  * Choice over the four existing `support` values.

Four rules are load-bearing and are enforced here rather than requested in prose:

  * Candidates come only from NUMBERED CANDIDATE assistant/tool transcript items. The
    fixed learner prefix is never quotable, exactly as the incumbent system prompt says.
  * An abstention is `score: null` with `support: "unverifiable"`. It is never a zero.
  * Every `reason`, `observation` and `uncertainty` string is an authored constant chosen
    by classification. The backend selects; it never writes.
  * A Choice carries at most 64 options (the gateway cap), so a long transcript narrows in stages
    (groups of items, then an item, then a sentence inside it) instead of overflowing.

Backend identity reuses `validate_classifier` from `benchmark_response_grading.py`
instead of inventing a second scheme. Reached over HTTP the judgement model is a
`model_api`; no new `kind` is added, so the existing validator keeps passing.

Transport-free by design: the caller injects `dispatch`, so tests need no network.
"""
