# Rating construction. An abstention is never a zero.
# ---------------------------------------------------------------------------------------

def abstain_rating(dimension, reason):
    """The single most important invariant in this module.

    "Cannot judge" is `score: null` plus `support: "unverifiable"`. Collapsing it into a 0
    would quietly turn "we do not know" into "the candidate did badly".
    """
    bench.require(reason in ABSTENTION_REASONS, "Unknown abstention reason")
    return {"dimension": dimension, "score": None, "reason": ABSTAIN_REASON,
            "support": "unverifiable", "uncertainty": UNCERTAINTIES[reason],
            "evidence": {"kind": "abstain", "transcript_index": None, "quote": None,
                         "observation": ABSTAIN_OBSERVATION}}


def error_ratings(rubric):
    """Every dimension unscored, with no provider text anywhere in the receipt."""
    return [{"dimension": dimension, "score": None, "reason": ERROR_REASON,
             "support": "unverifiable", "uncertainty": UNCERTAINTIES["backend-error"],
             "evidence": {"kind": "abstain", "transcript_index": None, "quote": None,
                          "observation": ""}}
            for dimension in rubric]


def resolve_rating(transcript, dimension, answers, cursor, *, floor, band):
    """Classify four typed answers into one rubric rating, or abstain with a named reason."""
    index = dimension["index"]
    name = dimension["dimension"]

    judgeable = answers.get(f"d{index}.judgeable")
    if judgeable is None:
        return abstain_rating(name, "missing-answer"), "missing-answer"
    if noul_decision(judgeable, band) != "yes":
        return abstain_rating(name, "not-judgeable"), "not-judgeable"

    score = answers.get(f"d{index}.score")
    if score is None:
        return abstain_rating(name, "missing-answer"), "missing-answer"
    if is_bimodal(score):
        return abstain_rating(name, "bimodal-distribution"), "bimodal-distribution"
    if score["confidence"] < floor:
        return abstain_rating(name, "below-confidence-floor"), "below-confidence-floor"
    level = modal_level(score)
    if level is None or level >= len(dimension["anchors"]):
        return abstain_rating(name, "missing-answer"), "missing-answer"

    support = answers.get(f"d{index}.support")
    if support is None:
        return abstain_rating(name, "missing-answer"), "missing-answer"
    if support["confidence"] < floor:
        return abstain_rating(name, "below-confidence-floor"), "below-confidence-floor"
    selected_support = modal_option(support)
    if selected_support not in SUPPORT_VALUES:
        selected_support = support["choice"]
    if selected_support == "unverifiable":
        # The incumbent validator already refuses a scored-but-unverifiable dimension.
        return abstain_rating(name, "unverifiable-support"), "unverifiable-support"

    candidate = cursor.get("selected")
    if candidate is None:
        # A level-0 rating is exactly the claim that the behavior is absent, so "nothing to
        # quote" is its evidence. Any credit above zero without a span is unevidenced, and
        # unevidenced credit is what the evidence discipline exists to stop.
        if level == 0:
            return ({"dimension": name, "score": 0, "reason": REASONS[("missing_behavior", 0)],
                     "support": selected_support, "uncertainty": None,
                     "evidence": {"kind": "missing_behavior", "transcript_index": None,
                                  "quote": None, "observation": MISSING_OBSERVATION}}, None)
        return abstain_rating(name, "no-candidate-selected"), "no-candidate-selected"

    quote = resolve_span(transcript, candidate)
    return ({"dimension": name, "score": level, "reason": REASONS[("quote", level)],
             "support": selected_support, "uncertainty": None,
             "evidence": {"kind": "quote", "transcript_index": candidate["transcript_index"],
                          "quote": quote, "observation": QUOTE_OBSERVATION}}, None)


def advance_cursor(transcript, cursor, answer, *, floor):
    """Apply one evidence Choice and decide whether another narrowing stage is needed."""
    if answer is None:
        cursor["resolved"] = True
        return
    option = modal_option(answer)
    if option not in cursor["options"] and option != NO_MATCH:
        option = answer["choice"]
    # A low-confidence selection is treated as no selection: acting on it would cite a span
    # the backend did not actually settle on.
    if option == NO_MATCH or answer["confidence"] < floor:
        cursor["resolved"] = True
        cursor["selected"] = None
        return
    node = cursor["options"][option]
    if "group" in node:
        cursor["nodes"] = list(node["group"])
        cursor["stage"] += 1
        cursor["stages"].append("group" if any("group" in n for n in cursor["nodes"]) else "item")
        return
    if cursor["phase"] == "sentences":
        cursor["selected"] = node
        cursor["resolved"] = True
        return
    cursor["item"] = node
    sentences = candidate_sentences(transcript, node) if len(node["text"]) > SENTENCE_STAGE_CHARS else []
    if len(sentences) < 2:
        cursor["selected"] = node
        cursor["resolved"] = True
        return
    cursor["phase"] = "sentences"
    cursor["nodes"] = candidate_tree(sentences, MAX_CHOICE_OPTIONS - 2)
    cursor["stage"] += 1
    cursor["stages"].append("sentence")


