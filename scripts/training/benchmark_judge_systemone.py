def accumulate_usage(total, usage):
    if not isinstance(usage, dict):
        return total
    for field in ("input_tokens", "output_tokens"):
        value = usage.get(field)
        if type(value) is int and value >= 0:
            total[field] = total.get(field, 0) + value
    return total


def run_review(case, transcript, dispatch, *, judge_model=SYSTEM_ONE_MODEL, floor,
               band=None, state=None, audit=None):
    """Batch, dispatch, narrow and classify. Returns ratings plus everything worth recording."""
    band = dict(JUDGEABLE_BAND if band is None else band)
    plan = build_plan(case, transcript, judge_model=judge_model, state=state)
    cursors = {dimension["index"]: new_cursor(plan) for dimension in plan["dimensions"]}
    questions = first_round_questions(plan, cursors)
    audit = {} if audit is None else audit
    audit.update(provider_calls=0, usage={}, usage_complete=True, returned_models=[], requests=[])
    answers, usage, requests = {}, audit["usage"], audit["requests"]
    returned_models = audit["returned_models"]

    def send(batch):
        body = request_body(batch, plan)
        requests.append(body)
        audit["provider_calls"] += 1
        try:
            raw = dispatch(body)
        except Exception:
            audit["usage_complete"] = False
            raise
        reported = raw.get("usage") if isinstance(raw, dict) else None
        if not isinstance(reported, dict) or any(type(reported.get(key)) is not int or reported[key] < 0
                                                  for key in ("input_tokens", "output_tokens")):
            audit["usage_complete"] = False
        accumulate_usage(usage, reported)
        if isinstance(raw, dict) and isinstance(raw.get("model"), str) and raw["model"] not in returned_models:
            returned_models.append(raw["model"])
        bench.require(len(returned_models) <= 1, "Judgement model changed during the review")
        decoded, _ = decode_response(batch, raw)
        answers.update(decoded)

    for batch in batch_questions(questions):
        send(batch)

    def apply_stage():
        for dimension in plan["dimensions"]:
            cursor = cursors[dimension["index"]]
            if cursor["resolved"]:
                continue
            advance_cursor(transcript, cursor,
                           answers.get(evidence_key(dimension, cursor["stage"])), floor=floor)

    apply_stage()
    for _ in range(MAX_NARROWING_ROUNDS):
        pending = {}
        for dimension in plan["dimensions"]:
            cursor = cursors[dimension["index"]]
            if cursor["resolved"]:
                continue
            question = evidence_question(dimension, cursor)
            if question is None:
                cursor["resolved"] = True
                continue
            pending[evidence_key(dimension, cursor["stage"])] = question
        if not pending:
            break
        for batch in batch_questions(pending):
            send(batch)
        apply_stage()

    ratings, abstentions, distributions = [], {}, {}
    for dimension in plan["dimensions"]:
        cursor = cursors[dimension["index"]]
        # An unresolved cursor after the round cap cites nothing rather than guessing.
        rating, reason = resolve_rating(transcript, dimension, answers, cursor,
                                        floor=floor, band=band)
        ratings.append(rating)
        if reason is not None:
            abstentions[dimension["dimension"]] = reason
        distributions[dimension["dimension"]] = {
            "score": answers.get(f'd{dimension["index"]}.score'),
            "judgeable": answers.get(f'd{dimension["index"]}.judgeable'),
            "support": answers.get(f'd{dimension["index"]}.support'),
            "evidence_stages": list(cursor["stages"]),
            "evidence_selected": (None if cursor["selected"] is None else
                                  {"transcript_index": cursor["selected"]["transcript_index"],
                                   "start": cursor["selected"]["start"],
                                   "end": cursor["selected"]["end"]}),
        }
    return {"plan": plan, "ratings": ratings, "abstentions": abstentions,
            "distributions": distributions, "requests": requests, "provider_calls": audit["provider_calls"],
            "usage_complete": audit["usage_complete"],
            "usage": usage or None, "narrowed": plan["narrowed"],
            "candidate_count": len(plan["candidates"]), "returned_models": returned_models}


def judge_case(case, transcript, dispatch, *, judge_model=SYSTEM_ONE_MODEL, candidate_model=None,
               manifest=None, confidence_floor=None, judgeable_band=None, validate=None):
    """Review one case with the typed backend, returning the incumbent's receipt shape.

    `validate` is the rubric validator applied to the finished ratings, defaulting to
    `benchmark_judge.validate_ratings`. Running selected evidence back through the incumbent
    validator is deliberate: the typed path has to satisfy exactly the same evidence
    discipline, not a weaker one written for itself.
    """
    if validate is None:
        import benchmark_judge
        validate = benchmark_judge.validate_ratings
    start = time.monotonic()
    receipt = {
        "schema_version": 1,
        "review_type": "AI semantic rubric review; not human ratings",
        "case_id": case["id"], "created_at": bench.now(),
        "judge_backend": "system-one", "judgement_protocol": PROTOCOL,
        "judge_model": judge_model, "judge_prompt_version": PROMPT_VERSION,
        "judge_prompt_sha256": PROMPT_SHA256,
        "bias": {"same_model_as_candidate": candidate_model == judge_model if candidate_model else None,
                 "note": "AI judge may favor its own model family/style; authored calibration is "
                         "not human validation or inter-rater reliability."},
        "status": "unscored", "ratings": [], "usage": None, "provider_calls": 0,
    }
    audit = {}
    try:
        resolved = default_manifest(judge_model) if manifest is None else validate_backend(manifest)
        floor = resolved["minimum_confidence"] if confidence_floor is None else confidence_floor
        band = dict(JUDGEABLE_BAND if judgeable_band is None else judgeable_band)
        settings = {**SETTINGS, "minimum_confidence": floor, "judgeable_noul_band": band}
        receipt["judge_settings"] = copy.deepcopy(settings)
        receipt["judge_settings_sha256"] = bench.digest(bench.canonical(settings))
        receipt["backend_manifest"] = copy.deepcopy(resolved)
        receipt["calibrated"] = resolved["calibration_sha256"] is not None
        receipt["calibration_note"] = (
            "Thresholds are filed per backend and question; an uncalibrated backend is reported "
            "as such and its floor is the predeclared manifest minimum, not a fitted one.")
        receipt["case_sha256"] = bench.digest(bench.canonical(review_material(case, transcript)["case"]))
        receipt["transcript_sha256"] = bench.digest(bench.canonical(transcript))
        review = run_review(case, transcript, dispatch, judge_model=judge_model, floor=floor,
                            band=band, audit=audit)
        receipt["judge_request_sha256"] = bench.digest(bench.canonical(review["requests"]))
        receipt["provider_calls"] = review["provider_calls"]
        receipt["usage"] = review["usage"]
        receipt["returned_models"] = review["returned_models"]
        receipt["ratings"] = validate(case, transcript, {"ratings": review["ratings"]})
        receipt["abstentions"] = review["abstentions"]
        receipt["distributions"] = review["distributions"]
        receipt["evidence"] = {"candidate_count": review["candidate_count"],
                               "narrowed": review["narrowed"]}
        receipt["status"] = "reviewed"
    except Exception as error:
        # Never serialize provider exception strings, which can contain credentials or the
        # learner's own text echoed back by an upstream error body.
        receipt["error"] = {"kind": "judge_request_or_validation_error", "type": type(error).__name__}
        receipt["ratings"] = error_ratings(case["rubric"])
        receipt["abstentions"] = {name: "backend-error" for name in case["rubric"]}
        receipt["status"] = "unscored"
    if audit:
        receipt["provider_calls"] = audit["provider_calls"]
        receipt["usage"] = audit["usage"] or None
        receipt["usage_complete"] = audit["usage_complete"]
        receipt["returned_models"] = audit["returned_models"]
        receipt["judge_request_sha256"] = bench.digest(bench.canonical(audit["requests"]))
    receipt["wall_seconds"] = time.monotonic() - start
    return receipt


def transport(key_file, *, endpoint=SYSTEM_ONE_ENDPOINT, timeout=120):
    """HTTP transport for the hosted backend. An upstream body never leaves this function."""
    bench.require(key_file.is_file() and not key_file.is_symlink()
                  and key_file.stat().st_mode & 0o077 == 0,
                  "Private mode-0600 API key file required")
    key = key_file.read_text().strip()
    bench.require(bool(key), "API key file empty")
    import httpx
    def dispatch(payload):
        with httpx.Client(timeout=timeout, follow_redirects=False) as client:
            response = client.post(endpoint, headers={"Authorization": "Bearer " + key},
                                   json=payload)
            bench.require(response.status_code == 200, "Judgement backend request failed")
            return response.json()
    return dispatch


def tape_key(payload):
    return bench.digest(bench.canonical(payload))


def fixture_dispatch(tape):
    """Taped replay keyed by the canonical request digest: offline and deterministic."""
    entries = dict(tape)
    def dispatch(payload):
        key = tape_key(payload)
        bench.require(key in entries, "No taped judgement response for this request")
        return copy.deepcopy(entries[key])
    return dispatch
